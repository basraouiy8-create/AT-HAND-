const I18N = {
  lang: "en",
  setLang(lang) {
    this.lang = DICTS[lang] ? lang : "en";
    document.documentElement.setAttribute("lang", this.lang);
  },
  t(key, params) {
    let str = (DICTS[this.lang] && DICTS[this.lang][key]) || DICTS.en[key] || key;
    if (params) {
      Object.keys(params).forEach((p) => {
        str = str.replace(`{${p}}`, params[p]);
      });
    }
    return str;
  }
};
